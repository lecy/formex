## Internal gazetteers for the person-name detectors in R/dt-person.R. These are
## curated frequency lists of common US given names and surnames -- the same
## reference-list modality as .us_cities (R/dt-address.R) and .metro_area_names
## (R/dt-geography.R), embedded here as literal vectors rather than in
## sysdata.rda so they are diff-reviewable and need no binary rebuild.
##
## SOURCES (public-domain US-government frequency data -- redistributable with
## no attribution or share-alike obligation; see data-raw/gazetteers.R):
##   .first_names  -- top 1000 US given names by lifetime births, Social Security
##                    Administration national baby-name data (1880-present, both
##                    sexes), bundled CC0 in the `babynames` package. The top
##                    1000 (min ~50k births) stays name-dominant into the tail,
##                    so recall rises without importing word-collision names.
##   .last_names   -- top 2000 US surnames by count, US Census Bureau
##                    "Frequently Occurring Surnames" 2010 (public domain; SSA
##                    publishes no surname list). Covers ~49% of the surname
##                    population mass; the tail stays surname-dominant (no
##                    word-collision), so recall rises cleanly.
##
## These are HEAD lists tuned for column-level detection: a person-name column
## is typed by the SHARE of its values that hit the gazetteer, not by exhaustive
## coverage. Regenerate both via data-raw/gazetteers.R; to widen recall further,
## append to the vectors below (they are plain, diff-reviewable source).
## Stored lowercased + de-duplicated + sorted at load so the literals can be
## written in readable title case and order does not matter.

## normalize a single name token for gazetteer membership: lowercase, strip to
## letters only (drops surrounding punctuation, initials' periods, hyphens).
#' @keywords internal
#' @noRd
.norm_name <- function(x) {
  x <- tolower(trimws(as.character(x)))
  gsub("[^a-z]", "", x)
}

